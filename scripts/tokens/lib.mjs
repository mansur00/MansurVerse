// Token pipeline library: load, resolve and generate. Used by tokens-build.mjs and tokens-check.mjs.
import { readFileSync } from 'node:fs';

const SOURCE = new URL('../../src/styles/tokens/tokens.json', import.meta.url);
const REF = /^\{([a-z0-9.-]+)\}$/;

// Group name to CSS variable prefix.
const PREFIX = {
  palette: 'palette',
  color: 'color',
  font: 'font',
  weight: 'font-weight',
  space: 'space',
  layout: 'layout',
  radius: 'radius',
  line: 'line',
  shape: 'shape',
  z: 'z',
  opacity: 'opacity',
  blur: 'blur',
  motion: 'motion',
  ease: 'ease',
  breakpoint: 'breakpoint',
};

export const loadTokens = () => JSON.parse(readFileSync(SOURCE, 'utf8'));

export const pair = (entry) => (typeof entry === 'string' ? { light: entry, dark: entry } : entry);

const lookup = (tokens, path) =>
  path.split('.').reduce((node, key) => (node == null ? undefined : node[key]), tokens);

export const varName = (group, name) =>
  group === 'component' ? `--${name}` : `--${PREFIX[group]}-${name}`;

// {group.name} becomes var(--group-name); any other value stays literal.
export function cssValue(value) {
  const match = REF.exec(String(value));
  if (!match) return String(value);
  const [group, ...rest] = match[1].split('.');
  if (!(group in PREFIX) && group !== 'component') throw new Error(`Unknown group in ${value}`);
  return `var(${varName(group, rest.join('.'))})`;
}

// Resolve a value down to a literal for one theme (used by the contrast check).
export function literal(tokens, value, theme) {
  const match = REF.exec(String(value));
  if (!match) return String(value);
  const target = lookup(tokens, match[1]);
  if (target === undefined) throw new Error(`Unresolved reference ${value}`);
  const next =
    typeof target === 'object' && target !== null && 'light' in target ? target[theme] : target;
  return literal(tokens, next, theme);
}

const header = '/* Generated by scripts/tokens-build.mjs from src/styles/tokens/tokens.json. Do not edit. */\n';
const decl = (name, value, indent = 2) => `${' '.repeat(indent)}${name}: ${value};`;
const toMs = (value) => (value.endsWith('ms') ? parseFloat(value) : parseFloat(value) * 1000);

export function generate(tokens) {
  const files = {};

  // tokens.css
  const root = [];
  const addGroup = (group) => {
    for (const [name, value] of Object.entries(tokens[group])) {
      root.push(decl(varName(group, name), cssValue(value)));
    }
  };
  [
    'palette', 'font', 'weight', 'space', 'layout', 'radius', 'line', 'shape', 'z', 'opacity', 'blur', 'motion', 'ease',
  ].forEach(addGroup);
  for (const [name, entry] of Object.entries(tokens.color)) {
    root.push(decl(varName('color', name), cssValue(pair(entry).light)));
  }
  for (const [name, value] of Object.entries(tokens.component)) {
    root.push(decl(varName('component', name), cssValue(value)));
  }
  const darkNames = Object.entries(tokens.color).filter(([, e]) => pair(e).dark !== pair(e).light);
  const dark = (indent) =>
    darkNames.map(([name, e]) => decl(varName('color', name), cssValue(pair(e).dark), indent)).join('\n');
  files['tokens.css'] =
    `${header}:root {\n  color-scheme: light;\n${root.join('\n')}\n}\n\n` +
    `:root[data-theme='dark'] {\n  color-scheme: dark;\n${dark(2)}\n}\n\n` +
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n    color-scheme: dark;\n${dark(4)}\n  }\n}\n`;

  // text-roles.css
  const vars = [];
  const classes = [];
  for (const [role, r] of Object.entries(tokens.text)) {
    const p = `--text-${role}`;
    vars.push(
      decl(`${p}-font`, `var(--font-${r.font})`),
      decl(`${p}-weight`, r.weight),
      decl(`${p}-size`, r.size),
      decl(`${p}-line`, r.line),
      decl(`${p}-tracking`, r.tracking),
    );
    const body = [
      decl('font-family', `var(${p}-font)`),
      decl('font-weight', `var(${p}-weight)`),
      decl('font-size', `var(${p}-size)`),
      decl('line-height', `var(${p}-line)`),
      decl('letter-spacing', `var(${p}-tracking)`),
    ];
    if (r.transform) body.push(decl('text-transform', r.transform));
    if (r.max) body.push(decl('max-width', r.max));
    classes.push(`.text-${role} {\n${body.join('\n')}\n}`);
  }
  files['text-roles.css'] = `${header}:root {\n${vars.join('\n')}\n}\n\n${classes.join('\n\n')}\n`;

  // theme.css (Tailwind 4): reset defaults so only tokens exist, then map tokens.
  const reset = [
    '--color-*', '--font-*', '--text-*', '--font-weight-*', '--radius-*', '--shadow-*', '--inset-shadow-*',
    '--drop-shadow-*', '--text-shadow-*', '--blur-*', '--ease-*', '--animate-*', '--breakpoint-*',
  ].map((name) => decl(name, 'initial'));
  const theme = [];
  theme.push(decl('--spacing', '4px'));
  for (const name of Object.keys(tokens.color)) {
    theme.push(decl(varName('color', name), cssValue(pair(tokens.color[name]).light)));
  }
  for (const name of Object.keys(tokens.font)) theme.push(decl(varName('font', name), tokens.font[name]));
  for (const name of Object.keys(tokens.weight)) theme.push(decl(varName('weight', name), tokens.weight[name]));
  for (const name of Object.keys(tokens.radius)) theme.push(decl(varName('radius', name), tokens.radius[name]));
  for (const name of Object.keys(tokens.blur)) theme.push(decl(varName('blur', name), tokens.blur[name]));
  for (const name of Object.keys(tokens.ease)) theme.push(decl(varName('ease', name), tokens.ease[name]));
  for (const name of Object.keys(tokens.breakpoint)) {
    theme.push(decl(varName('breakpoint', name), tokens.breakpoint[name]));
  }
  files['theme.css'] = `${header}@theme {\n${reset.join('\n')}\n${theme.join('\n')}\n}\n`;

  // tokens.ts (constants for JS, so GSAP code never uses literals)
  const motion = Object.fromEntries(Object.entries(tokens.motion).map(([k, v]) => [k, toMs(v)]));
  const points = (v) => v.match(/[\d.]+/g).map(Number);
  const easePoints = Object.fromEntries(Object.entries(tokens.ease).map(([k, v]) => [k, points(v)]));
  const num = (group) => Object.fromEntries(Object.entries(tokens[group]).map(([k, v]) => [k, parseFloat(v)]));
  files['tokens.ts'] =
    `// Generated by scripts/tokens-build.mjs. Do not edit.\n` +
    `export const motionMs = ${JSON.stringify(motion, null, 2)} as const;\n\n` +
    `export const ease = ${JSON.stringify(tokens.ease, null, 2)} as const;\n\n` +
    `export const easePoints = ${JSON.stringify(easePoints, null, 2)} as const;\n\n` +
    `export const breakpoints = ${JSON.stringify(num('breakpoint'), null, 2)} as const;\n\n` +
    `export const zIndex = ${JSON.stringify(num('z'), null, 2)} as const;\n`;

  // tokens.summary.json (for the /styleguide page)
  const colors = Object.entries(tokens.color).map(([name, e]) => ({
    name,
    light: literal(tokens, pair(e).light, 'light'),
    dark: literal(tokens, pair(e).dark, 'dark'),
  }));
  const summary = {
    palette: tokens.palette,
    colors,
    fonts: tokens.font,
    roles: Object.entries(tokens.text).map(([name, r]) => ({ name, ...r })),
    space: tokens.space,
    radius: tokens.radius,
    line: tokens.line,
    shape: tokens.shape,
    z: tokens.z,
    opacity: tokens.opacity,
    motion: tokens.motion,
    ease: tokens.ease,
    breakpoint: tokens.breakpoint,
    components: tokens.component,
  };
  files['tokens.summary.json'] = `${JSON.stringify(summary, null, 2)}\n`;

  return files;
}

// WCAG relative luminance and contrast ratio for #rrggbb colours.
const channel = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
export function luminance(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`Contrast pairs need #rrggbb colours, got ${hex}`);
  const n = parseInt(m[1], 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}
export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}
